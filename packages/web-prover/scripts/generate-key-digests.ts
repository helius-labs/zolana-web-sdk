// Writes src/key-digests.ts from the pinned zopro-keys.lock. Run after a
// key rotation; test/key-digests.test.ts fails until the two agree.
import { readFile, writeFile } from "node:fs/promises";

/** One zopro key file and the gnark proving key it was built from. */
interface LockEntry {
  readonly file: string;
  readonly size: number;
  readonly sha256: string;
  readonly key_sha256: string;
}

interface Lock {
  readonly prefix: string;
  readonly baseUrl: string;
  readonly keys: Record<string, LockEntry>;
}

const lockUrl = new URL("../../../zopro-keys.lock", import.meta.url);
const outputUrl = new URL("../src/key-digests.ts", import.meta.url);

export const browserKey = /^(transfer_confidential_\d+_\d+|merge_\d+_1)\.key$/u;

async function readLock(): Promise<Lock> {
  return JSON.parse(await readFile(lockUrl, "utf8")) as Lock;
}

/** The key set's version folder, e.g. `3a1c88f90f609eb1` from `proving-keys/3a1c88f90f609eb1`. */
export async function lockedKeySet(): Promise<string> {
  const keySet = (await readLock()).prefix.split("/").at(-1);
  if (keySet === undefined || !/^[0-9a-f]+$/u.test(keySet)) throw new Error("Unexpected lock prefix");
  return keySet;
}

/** The CDN folder of the pinned key set. */
export async function lockedKeyBaseUrl(): Promise<string> {
  const { baseUrl } = await readLock();
  if (!baseUrl.startsWith("https://") || !baseUrl.endsWith(`/${await lockedKeySet()}/`)) {
    throw new Error("zopro-keys.lock baseUrl does not name the lock's key set");
  }
  return baseUrl;
}

export async function lockedBrowserKeys(): Promise<
  Record<string, { file: string; size: number; sha256: string; keySha256: string }>
> {
  const lock = await readLock();
  const keys = Object.entries(lock.keys)
    .filter(([name]) => browserKey.test(name))
    .sort(([a], [b]) => a.localeCompare(b));
  return Object.fromEntries(
    keys.map(([name, { file, size, sha256, key_sha256 }]) => [
      name,
      { file, size, sha256, keySha256: key_sha256 },
    ]),
  );
}

if (import.meta.main) {
  const keys = await lockedBrowserKeys();
  const entries = Object.entries(keys).map(
    ([name, { file, size, sha256, keySha256 }]) =>
      `  "${name}": {\n    file: "${file}",\n    size: ${String(size)},\n    sha256: "${sha256}",\n    keySha256: "${keySha256}",\n  },`,
  );
  await writeFile(
    outputUrl,
    `// Generated by scripts/generate-key-digests.ts from zopro-keys.lock; do not edit.

/** The pinned key set's version folder on the proving-keys CDN. */
export const KEY_SET = "${await lockedKeySet()}";

/** Where the pinned key set is served from; the default \`keyBaseUrl\`. */
export const KEY_BASE_URL = "${await lockedKeyBaseUrl()}";

/**
 * Every proving key the browser prover can load, by the gnark key's name: its
 * zopro key file, that file's size and sha256, and the sha256 of the gnark key
 * it was built from, which proofs report.
 */
export const KEY_DIGESTS: Readonly<
  Record<string, Readonly<{ file: string; size: number; sha256: string; keySha256: string }>>
> = Object.freeze({
${entries.join("\n")}
});
`,
  );
  console.log(`Wrote ${String(entries.length)} key digests to src/key-digests.ts`);
}
